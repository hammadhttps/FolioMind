import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/*
 * Regenerates `src/fonts.generated.ts` from the WOFF2 files in `fonts/`, so
 * templates embed fonts as data URIs and the renderer fetches nothing
 * (blueprint Section 26). Run with `pnpm --filter @foliomind/pdf fonts`.
 */

const root = path.resolve(import.meta.dirname, "..");
const fonts = {
  interRegular: "inter-latin-400-normal.woff2",
  interSemiBold: "inter-latin-600-normal.woff2",
  serifRegular: "source-serif-4-latin-400-normal.woff2",
  serifItalic: "source-serif-4-latin-400-italic.woff2",
  serifSemiBold: "source-serif-4-latin-600-normal.woff2",
};

const lines = [
  "// Generated by scripts/embed-fonts.ts from fonts/*.woff2 (SIL Open Font License). Do not edit.",
  "",
];
for (const [name, file] of Object.entries(fonts)) {
  const base64 = readFileSync(path.join(root, "fonts", file)).toString("base64");
  lines.push(`export const ${name} = "data:font/woff2;base64,${base64}";`);
}
writeFileSync(path.join(root, "src", "fonts.generated.ts"), `${lines.join("\n")}\n`);
console.log(`wrote ${Object.keys(fonts).length} fonts`);
